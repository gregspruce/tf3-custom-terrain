--[[
custom_terrain_diag.script.lua - Diagnostics node for "Custom Terrain (Experimental)".

WHY
  Removes human error from in-game testing: on every map generation it writes ONE machine-readable
  line to the game log (UD/crash_dump/stdout.txt):
      CT_DIAG {"v":1, "sliders":{...}, "map":{...}, "stats":{...}, "rivers":{...}}
  containing every slider value as received by the graph (validates the slider convention), the
  map seed/size, and terrain statistics sampled from the FINAL heightmap (water share, height
  percentiles, buildable-grade shares, biome shares, river coverage). the project's 
  analyze_tests.py parses these lines (plus the engine's own "Pipeline took"/memory lines) into a
  report and compares them with exported heightmaps and offline previews.

SAFETY
  Everything runs inside pcall and the node always outputs 0. Its output is wired into a param that
  is 0 anyway ('New Remap map #298'.from.x), only so the engine evaluates this node after the
  terrain is complete. A failure here can never change or break the terrain.

The engine's Lua is 5.2.2; plain Lua, no requires. Inputs are generated by tools/build_exp.py
(one Float per slider: s_<key>), plus maps: height, water, biome1..4 (hard regions), river.
]]

function data()

local function emit(line)
	-- generator script log.verbose did not reach stdout.txt in testing; try several channels
	local ok = false
	if log and log.message then ok = pcall(log.message, line) or ok end
	if log and log.warning then ok = pcall(log.warning, line) or ok end
	if print then pcall(print, line) end
end

local function num(v)
	if v ~= v then return "null" end              -- NaN
	if v == math.huge or v == -math.huge then return "null" end
	return string.format("%.6g", v)
end

local function jsonObj(t, keys)
	local parts = {}
	for _, k in ipairs(keys) do
		local v = t[k]
		if type(v) == "number" then parts[#parts + 1] = string.format("%q:%s", k, num(v))
		elseif type(v) == "string" then parts[#parts + 1] = string.format("%q:%q", k, v)
		elseif type(v) == "boolean" then parts[#parts + 1] = string.format("%q:%s", k, v and "true" or "false")
		end
	end
	return "{" .. table.concat(parts, ",") .. "}"
end

local function sortedKeys(t)
	local k = {}
	for key in pairs(t) do k[#k + 1] = key end
	table.sort(k)
	return k
end

local function run(params, inputs)
	local bmin, bmax = inputs.boundsMin.point, inputs.boundsMax.point
	local W, H = bmax.x - bmin.x, bmax.y - bmin.y

	-- sliders: every input named s_<key>
	local sliders = {}
	for key, inp in pairs(inputs) do
		if type(key) == "string" and key:sub(1, 2) == "s_" and inp and inp.value ~= nil then
			sliders[key:sub(3)] = inp.value
		end
	end

	local function has(name) return inputs[name] and inputs[name].map and not inputs[name].map:isEmpty() end
	local function get(name, x, y) return inputs[name].map:get(api.type.Vec2f.new(x, y)) end

	-- sample the final terrain on an N x N grid (cell-centred), plus 8 m offsets for local grade
	local N = 72
	local dx, dy = W / N, H / N
	local n, nLand, nWater = 0, 0, 0
	local hs = {}
	local g3, g85, g30 = 0, 0, 0
	local b = { 0, 0, 0, 0 }
	local riverCells = 0
	local hmin, hmax = math.huge, -math.huge
	local deepest = 0
	for i = 0, N - 1 do
		for j = 0, N - 1 do
			local x = bmin.x + (i + 0.5) * dx
			local y = bmin.y + (j + 0.5) * dy
			n = n + 1
			local h = has("height") and get("height", x, y) or 0
			if h < hmin then hmin = h end
			if h > hmax then hmax = h end
			local w = has("water") and get("water", x, y) or 0
			if h <= 0.0 or w > 0.5 then
				nWater = nWater + 1
				if h < deepest then deepest = h end
			else
				nLand = nLand + 1
				hs[#hs + 1] = h
				if has("height") then
					local hx = get("height", x + 8, y)
					local hy = get("height", x, y + 8)
					local grade = math.sqrt(((hx - h) / 8) ^ 2 + ((hy - h) / 8) ^ 2)
					if grade < 0.03 then g3 = g3 + 1 end
					if grade < 0.085 then g85 = g85 + 1 end
					if grade > 0.30 then g30 = g30 + 1 end
				end
				for k = 1, 4 do
					local nm = "biome" .. k
					if has(nm) and get(nm, x, y) > 0.5 then b[k] = b[k] + 1 end
				end
			end
			if has("river") and get("river", x, y) < -0.05 then riverCells = riverCells + 1 end
		end
	end
	table.sort(hs)
	local function pct(p)
		if #hs == 0 then return 0 end
		return hs[math.max(1, math.min(#hs, math.floor(p * #hs + 0.5)))]
	end
	local L = math.max(1, nLand)
	local stats = {
		samples = n, water_pct = 100 * nWater / n,
		land_grade_lt3_pct = 100 * g3 / L, land_grade_lt8_5_pct = 100 * g85 / L,
		land_grade_gt30_pct = 100 * g30 / L,
		h_min = hmin, h_max = hmax, h_land_p10 = pct(0.1), h_land_p50 = pct(0.5),
		h_land_p90 = pct(0.9), h_land_p99 = pct(0.99), deepest = deepest,
		biome1_pct = 100 * b[1] / L, biome2_pct = 100 * b[2] / L,
		biome3_pct = 100 * b[3] / L, biome4_pct = 100 * b[4] / L,
		river_cells_pct = 100 * riverCells / n,
	}
	local map = {
		seed = inputs.seed and inputs.seed.value or -1,
		width_m = W, height_m = H, tiles_x = W / 256, tiles_y = H / 256,
	}
	local clock = (os and os.clock) and os.clock() or -1
	local line = "CT_DIAG {\"v\":1,\"mod\":\"custom_terrain_experimental\""
		.. ",\"lua\":" .. string.format("%q", _VERSION or "?")
		.. ",\"clock\":" .. num(clock)
		.. ",\"map\":" .. jsonObj(map, sortedKeys(map))
		.. ",\"sliders\":" .. jsonObj(sliders, sortedKeys(sliders))
		.. ",\"stats\":" .. jsonObj(stats, sortedKeys(stats))
		.. "}"
	emit(line)
end

local function applyFn(params, inputs, captureParams)
	local ok, err = pcall(run, params, inputs)
	if not ok then emit("CT_DIAG_ERROR " .. tostring(err)) end
	return { { 1, 0 } }   -- output type 1 = Float (2 = Point, 3 = PointCloud)
end

return {
	diagnostics = {
		applyFn = applyFn,
	},
}
end
